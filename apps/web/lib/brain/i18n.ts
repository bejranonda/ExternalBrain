export type Vars = Record<string, string | number>;

export function translate(lang: Lang, path: string, vars?: Vars): string {
  const parts = path.split(".");
  const walk = (dict: unknown) => {
    let o: unknown = dict;
    for (const p of parts) {
      if (o && typeof o === "object" && p in (o as Record<string, unknown>)) {
        o = (o as Record<string, unknown>)[p];
      } else {
        return undefined;
      }
    }
    return o;
  };
  let o = walk(I18N[lang]);
  if (o == null) o = walk(I18N.en);
  if (typeof o === "string") {
    return vars
      ? o.replace(/\{\{(\w+)\}\}/g, (_, k) => String(vars[k] ?? ""))
      : o;
  }
  return typeof o === "string" ? o : path;
}

export const LangContext = createContext<Lang>("en");
export function useLang() {
  return useContext(LangContext);
}
export function useT() {
  const lang = useLang();
  return (path: string, vars?: Vars) => translate(lang, path, vars);
}
